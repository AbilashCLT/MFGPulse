            WHEN MFGPULSE_DB.ML_MODELS.COMPUTE_FATIGUE_SCORE(
                rs.VIB_CREST_FACTOR_6H, rs.VIB_COEFF_VAR_6H, rs.VIB_PEAK_TO_PEAK_6H,
