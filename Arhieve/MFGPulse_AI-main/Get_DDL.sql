        FROM MFGPULSE_DB.RAW_IT.PART_SUPPLIERS ps2 WHERE ps2.PREFERRED_SUPPLIER = TRUE
        QUALIFY ROW_NUMBER() OVER (PARTITION BY ps2.PART_ID ORDER BY ps2.UNIT_COST) = 1
    ) ps ON cp.PART_ID = ps.PART_ID
    LEFT JOIN (
