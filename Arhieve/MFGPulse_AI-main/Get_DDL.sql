CREATE OR REPLACE PROCEDURE "SEND_MFGPULSE_EMAIL"("P_SUBJECT" VARCHAR, "P_BODY_HTML" VARCHAR, "P_RECIPIENTS" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
    IF (:p_recipients IS NULL OR LENGTH(TRIM(:p_recipients)) = 0) THEN
        RETURN ''SKIPPED: No recipients'';
    END IF;
