 as
WITH last_maintenance AS (
    SELECT 
        asset_id,
        MAX(CASE WHEN status = 'completed' THEN completed_date END) AS last_maint_date,
        COUNT(*) AS total_wo_count,
        COUNT(CASE WHEN wo_type = 'emergency' THEN 1 END) AS emergency_count,
