create or replace view COST_IMPACT(
	ASSETS_WITH_EARLY_DETECTION,
	AVG_EARLY_DETECTION_DAYS,
	MAX_EARLY_DETECTION_DAYS,
	TOTAL_COST_AVOIDED,
	DOWNTIME_HOURS_PREVENTED,
	AVG_COST_PER_EMERGENCY_FAILURE,
