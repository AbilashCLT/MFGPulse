WITH demand_by_part AS (
    SELECT pr.PART_ID, pr.PART_NAME, pr.SUPPLIER_ID, pr.SUPPLIER_NAME,
        pr.LEAD_TIME_DAYS, pr.UNIT_COST,
        COUNT(DISTINCT pr.ASSET_ID) AS ASSET_COUNT,
