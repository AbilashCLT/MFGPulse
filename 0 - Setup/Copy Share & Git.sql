-- ============================================================
-- Copy MFGPULSE_DB_SHARED (shared DB) → MFGPULSE_DB (local)
-- ============================================================

-- 1. Create the target database
CREATE DATABASE IF NOT EXISTS MFGPULSE_DB;

-- 2. Create schemas
