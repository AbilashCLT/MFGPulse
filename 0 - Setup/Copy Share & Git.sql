-- 4. Grant access
GRANT ALL PRIVILEGES ON DATABASE MFGPULSE_DB TO ROLE SYSADMIN;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE MFGPULSE_DB TO ROLE SYSADMIN;
GRANT ALL PRIVILEGES ON ALL TABLES IN DATABASE MFGPULSE_DB TO ROLE SYSADMIN;

-- 5. Verify row counts
SELECT TABLE_SCHEMA, TABLE_NAME, ROW_COUNT
FROM MFGPULSE_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE' AND TABLE_SCHEMA != 'INFORMATION_SCHEMA'
ORDER BY TABLE_SCHEMA, TABLE_NAME;

DROP API INTEGRATION "MFGPulse";
CREATE OR REPLACE API INTEGRATION "MFGPulse"
  API_PROVIDER = git_https_api
  API_ALLOWED_PREFIXES = ('https://github.com/AbilashCLT')
  API_USER_AUTHENTICATION = (TYPE = SNOWFLAKE_GITHUB_APP)
  ENABLED = TRUE;

SHOW INTEGRATIONS LIKE '%MFGPulse%';